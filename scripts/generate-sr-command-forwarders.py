"""Forward otherwise unobserved vkCmd calls to the FSR4 continuation.

Generated source is checked in: a normal build does not need Python. Signatures
come from the project's pinned Vulkan registry, not from executable code.
"""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
observer = (root / "src/vulkan_observer.cpp").read_text(encoding="utf-8")
core = (root / "third_party/Vulkan-Headers/include/vulkan/vulkan_core.h").read_text(encoding="utf-8")
available = set(re.findall(r"PFN_(vkCmd\w+)\)", core))
existing = set(re.findall(r"HOOK\((vkCmd\w+)\)", observer))
commands = ET.parse(root / "third_party/Vulkan-Headers/registry/vk.xml").getroot().find("commands")
definitions = {c.get("name") or c.findtext("proto/name"): c for c in commands}
lines = ["// Generated by scripts/generate-sr-command-forwarders.py; do not edit.",
         "// No resource inspection or logging. Only FSR4 enables these continuations."]
names = sorted(available - existing)
for name in names:
    definition = definitions[name]
    while definition.get("alias"):
        definition = definitions[definition.get("alias")]
    result = definition.findtext("proto/type")
    parameters = definition.findall("param")
    declarations = ["".join(p.itertext()).strip() for p in parameters]
    arguments = [p.findtext("name") for p in parameters]
    assert parameters[0].findtext("type") == "VkCommandBuffer", name
    first = arguments[0]
    fail = "return;" if result == "void" else "return VK_ERROR_EXTENSION_NOT_PRESENT;"
    lines += [f"VKAPI_ATTR {result} VKAPI_CALL fsr4_forward_{name}({','.join(declarations)}) {{",
              f"    auto* state=findDevice({first});if(!state){{{fail}}}",
              f"    static thread_local std::uint64_t incarnation;static thread_local PFN_{name} next;",
              f"    if(incarnation!=state->deviceIncarnation){{next=reinterpret_cast<PFN_{name}>(state->gdpa(state->device,\"{name}\"));incarnation=state->deviceIncarnation;}}",
              f"    if(!next){{{fail}}}",
              f"    {'return ' if result != 'void' else ''}next(srCommand(state,{first}){',' if len(arguments)>1 else ''}{','.join(arguments[1:])});",
              "}", f"static_assert(std::is_same_v<decltype(&fsr4_forward_{name}),PFN_{name}>);"]
lines += ["PFN_vkVoidFunction fsr4AdditionalCommandHook(const char* name)noexcept {",
          "    if(xess_vk::sr_backend::startup()!=xess_vk::sr_backend::Kind::Fsr4XmxLite)return nullptr;"]
for name in names:
    lines.append(f'    if(std::strcmp(name,"{name}")==0)return reinterpret_cast<PFN_vkVoidFunction>(&fsr4_forward_{name});')
lines += ["    return nullptr;", "}", ""]
output = root / "src/fsr4_command_forwarders.inc"
output.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {len(names)} statically typed continuation forwarders.")
